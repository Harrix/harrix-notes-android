def escape_xml(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", r"\'")
    )


def write_locale(folder: str, mapping: dict) -> None:
    merged = {**EN, **mapping}
    missing = [k for k in BASE_ORDER if k not in merged and k not in COMMON_SKIP]
    # COMMON_SKIP keys come from EN
    for key in BASE_ORDER:
        if key not in merged:
            raise SystemExit(f"Missing key {key} in {folder}")
    out_dir = ROOT / folder
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for key in BASE_ORDER:
        value = escape_xml(merged[key])
        lines.append(f'    <string name="{key}">{value}</string>')
    lines.append("</resources>")
    (out_dir / "strings.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {folder}/strings.xml ({len(BASE_ORDER)} strings)")


def main() -> None:
    for folder, mapping in TRANSLATIONS.items():
        write_locale(folder, mapping)


if __name__ == "__main__":
    main()
